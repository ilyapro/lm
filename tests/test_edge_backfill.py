from living_memory.storage import MemoryStore

SCOPE = "project:edge-backfill-tests"


def _store(tmp_path: Path) -> MemoryStore:
    return MemoryStore(tmp_path / "memory.sqlite3")


def _remember(store: MemoryStore, content: str, **context: Any) -> Node:
    context.setdefault("scope", SCOPE)
    return store.append_trace(content, context)


def _edge_rows(store: MemoryStore) -> list[tuple[Any, ...]]:
    """Full connection rows as plain tuples for byte-identity comparison."""

    return [
        tuple(row)
        for row in store.connection.execute(
            "SELECT id, source_id, target_id, type, weight, metadata, "
            "created_at, updated_at FROM connections ORDER BY id"
        ).fetchall()
    ]


def _only(store: MemoryStore, **kwargs: Any) -> Connection:
    edges = store.list_connections(**kwargs)
    assert len(edges) == 1, f"expected one edge, got {len(edges)}"
    return edges[0]


def _seed_typed_material(store: MemoryStore) -> dict[str, Node]:
    """Seed references and shared sources, plus independent problem/fix labels."""

    stale = _remember(store, "The runner lock lives in /tmp/runner.lock")
    correction = _remember(
        store, f"CORRECTION to trace {stale.id}: the lock lives in /var/lock, NOT /tmp"
    )
    referrer = _remember(store, "Background job internals note")
    referee_note = _remember(
        store, f"Re-run building on {referrer.id} finished cleanly today."
    )
    commit_a = _remember(store, "Implementation of the widget", commit="abc1234def0")
    commit_b = _remember(store, "Verification of the widget change", commit="abc1234def0")
    file_a = _remember(store, "Design note for the loader", files=["src/loader.py"])
    file_b = _remember(store, "Bugfix in the loader", files=["src/loader.py"])
    problem = _remember(
        store,
        "Dead pid left node_status stuck",
        type="root_cause",
        task="recover-node",
        timestamp="2026-06-01T10:00:00Z",
    )
    fix = _remember(
        store,
        "Recover interrupted tree node status by clearing the pid",
        type="fix",
        task="recover-node",
        timestamp="2026-06-01T10:02:00Z",
    )
    return {
        "stale": stale,
        "correction": correction,
        "referrer": referrer,
        "referee_note": referee_note,
        "commit_a": commit_a,
        "commit_b": commit_b,
        "file_a": file_a,
        "file_b": file_b,
        "problem": problem,
        "fix": fix,
    }


# --- correctness: each go-rule produces a marked, correctly-typed edge --------


def test_backfill_derives_all_go_rules_with_marker(tmp_path: Path) -> None:
    with _store(tmp_path) as store:
        nodes = _seed_typed_material(store)
        report = backfill_edges(store, apply=True)

        mention = _only(
            store, source_id=nodes["correction"].id, target_id=nodes["stale"].id,
            relation_type="related",
        )
        assert mention.metadata["kind"] == CONTENT_REFERENCE_KIND
        assert mention.metadata["basis"] == BACKFILL_BASIS
        assert store.list_supersedes_pairs([nodes["stale"].id]) == []

        # R6: plain citation -> directed related, kind preserved for traversal.
        r6 = _only(
            store,
            source_id=nodes["referee_note"].id,
            target_id=nodes["referrer"].id,
            relation_type="related",
        )
        assert r6.metadata["kind"] == CONTENT_REFERENCE_KIND
        assert r6.metadata["basis"] == BACKFILL_BASIS

        # R4a: same commit -> undirected related, rule basis preserved.
        src, tgt = sorted((nodes["commit_a"].id, nodes["commit_b"].id))
        r4a = _only(store, source_id=src, target_id=tgt, relation_type="related")
        assert r4a.metadata["basis"] == BACKFILL_BASIS
        assert r4a.metadata["rule_basis"] == SAME_COMMIT_BASIS
        assert r4a.metadata["commit"] == "abc1234"

        # R4b: shared files -> undirected related.
        fsrc, ftgt = sorted((nodes["file_a"].id, nodes["file_b"].id))
        r4b = _only(store, source_id=fsrc, target_id=ftgt, relation_type="related")
        assert r4b.metadata["rule_basis"] == SHARED_FILES_BASIS
        assert r4b.metadata["files"] == ["src/loader.py"]

        assert store.list_connections(
            source_id=nodes["problem"].id, target_id=nodes["fix"].id,
            relation_type="caused",
        ) == []

        by_rule = report["rules"]
        assert by_rule["R4a"]["new"] == 1
        assert by_rule["R4b"]["new"] == 1
        assert by_rule["R6"]["new"] == 2
        assert report["totals"]["new_rows"] == 4


def test_backfill_marker_never_touches_kind_so_traversal_holds(tmp_path: Path) -> None:
    """The rollback marker rides in `basis`; the `kind` retrieval reads survives."""

    with _store(tmp_path) as store:
        referrer = _remember(store, "Original design decision")
        citer = _remember(store, f"Plan extends {referrer.id} with the new curve.")
        backfill_edges(store, apply=True)

        edge = _only(
            store,
            source_id=citer.id,
            target_id=referrer.id,
            relation_type="related",
        )
        # forward referrer->referee 0.75, backward 0.9 (retrieval._traversal).
        forward = _traversal(edge, citer.id, causal_mode=False)
        backward = _traversal(edge, referrer.id, causal_mode=False)
        assert forward is not None and round(forward[1], 6) == round(edge.weight * 0.75, 6)
        assert backward is not None and round(backward[1], 6) == round(edge.weight * 0.9, 6)


# --- idempotency --------------------------------------------------------------


def test_backfill_idempotent_second_run_zero_new(tmp_path: Path) -> None:
    with _store(tmp_path) as store:
        _seed_typed_material(store)
        first = backfill_edges(store, apply=True)
        assert first["totals"]["new_rows"] > 0
        after_first = _edge_rows(store)

        second = backfill_edges(store, apply=True)
        assert second["totals"]["new_rows"] == 0
        assert _edge_rows(store) == after_first


# --- additive guarantee: existing edges byte-identical ------------------------


def test_backfill_leaves_existing_edges_byte_identical(tmp_path: Path) -> None:
    with _store(tmp_path) as store:
        nodes = _seed_typed_material(store)
        # An unrelated hand edge, and one that collides with a rule's output.
        unrelated = store.create_connection(
            nodes["referrer"].id,
            nodes["stale"].id,
            "related",
            weight=0.42,
            metadata={"kind": "manual"},
        )
        colliding = store.create_connection(
            nodes["correction"].id,
            nodes["stale"].id,
            "related",
            weight=0.3,
            metadata={"kind": "manual"},
        )
        before = {row[0]: row for row in _edge_rows(store)}

        report = backfill_edges(store, apply=True)
        assert report["totals"]["new_rows"] > 0
        after = {row[0]: row for row in _edge_rows(store)}

        # Every pre-existing row is unchanged, including the colliding one:
        # the existing reference was skipped, not reweighted to 0.9.
        for edge_id, row in before.items():
            assert after[edge_id] == row
        assert after[colliding.id][4] == 0.3  # weight untouched
        assert '"manual"' in after[colliding.id][5]  # metadata untouched
        assert unrelated.id in after


@pytest.mark.parametrize(
    "metadata",
    [
        {"kind": "drain_near_duplicate", "cosine": 1.0},
        {"kind": "duplicate_content", "basis": "procedure_key"},
        {"rule": "R1c", "kind": "content_correction"},
        {"by": "lm_collapse_near_dups.py", "reason": "near-duplicate collapse"},
    ],
)
def test_backfill_preserves_historical_supersedes_without_reauthorizing_it(tmp_path, metadata):
    with _store(tmp_path) as store:
        old = _remember(store, "Dashboard restart requires approval.")
        note = _remember(store, f"Not a correction to {old.id}; approval is still required.")
        historical = store.create_connection(note.id, old.id, "supersedes", metadata=metadata)

        plan = backfill_edges(store)
        assert plan["totals"]["new_rows"] == 1
        assert plan["totals"]["semantic_updates"] == 0
        assert store.get_connection(historical.id) == historical

        applied = backfill_edges(store, apply=True)
        assert applied["totals"]["new_rows"] == 1
        assert store.get_connection(historical.id) == historical
        assert store.list_supersedes_pairs([old.id]) == []
        reference = _only(store, source_id=note.id, relation_type="related")
        assert reference.metadata["kind"] == CONTENT_REFERENCE_KIND
        after = _edge_rows(store)
        assert backfill_edges(store, apply=True)["totals"]["new_rows"] == 0
        assert _edge_rows(store) == after


@pytest.mark.parametrize("metadata", [{}, {"kind": "unknown"}, {"by": "lm_collapse_near_dups.py"}])
def test_backfill_preserves_explicit_correction_and_adds_reference(tmp_path, metadata):
    with _store(tmp_path) as store:
        old = _remember(store, "The lock is in /tmp.")
        new = _remember(store, f"Correction to {old.id}: use /var/lock.")
        explicit = store.create_connection(new.id, old.id, "supersedes", weight=.4, metadata=metadata)

        report = backfill_edges(store, apply=True)

        assert report["totals"]["new_rows"] == 1
        assert report["totals"]["semantic_updates"] == 0
        assert store.get_connection(explicit.id) == explicit
        assert store.list_supersedes_pairs([old.id]) == [(new.id, old.id)]


# --- dry-run writes nothing ---------------------------------------------------


def test_dry_run_writes_nothing_but_reports_plan(tmp_path: Path) -> None:
    with _store(tmp_path) as store:
        _seed_typed_material(store)
        before = _edge_rows(store)

        report = backfill_edges(store, apply=False)

        assert report["mode"] == "dry-run"
        assert report["applied"] is False
        assert report["totals"]["new_rows"] > 0  # it *would* have inserted
        assert report["typed_share"]["after"]["projected"] is True
        assert _edge_rows(store) == before  # ... but wrote nothing


