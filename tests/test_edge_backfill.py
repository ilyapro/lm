@pytest.mark.parametrize("kind", ["empty", "invalid", "missing_table", "missing_column"])
def test_preview_rejects_unsupported_database(preview_db, tmp_path, monkeypatch, kind):
    path = preview_db
    if kind in {"empty", "invalid"}:
        path = tmp_path / "unsupported.sqlite3"
        path.write_bytes(b"not SQLite" if kind == "invalid" else b"")
    else:
        with closing(sqlite3.connect(path)) as conn, conn:
            conn.execute(
                "DROP TABLE connections" if kind == "missing_table"
                else "ALTER TABLE connections DROP COLUMN metadata"
            )
    before = path.read_bytes() if kind == "invalid" else _snapshot(path)
    stores = _capture_store(monkeypatch)
    with pytest.raises(sqlite3.DatabaseError):
        run_backfill(path)
    _assert_closed(stores)
    output = tmp_path / "audit.json"
    for flags in ([], ["--dry-run"]):
        result = _cli(path, *flags, "--report", str(output))
        assert result.returncode == 2
        assert "derive-edges:" in result.stderr
        assert result.stdout == ""
        assert not output.exists()
    assert (path.read_bytes() if kind == "invalid" else _snapshot(path)) == before


@pytest.mark.parametrize("apply", [False, True])
@pytest.mark.parametrize("fail", [False, True])
def test_run_backfill_closes_store(preview_db, monkeypatch, apply, fail):
    stores = _capture_store(monkeypatch, apply)
    if fail:
        def failed(*args, **kwargs):
            raise RuntimeError("derivation failed")

        monkeypatch.setattr(edge_backfill, "backfill_edges", failed)
        with pytest.raises(RuntimeError, match="derivation failed"):
            run_backfill(preview_db, apply=apply)
    else:
        assert run_backfill(preview_db, apply=apply)["applied"] is apply
    _assert_closed(stores)


