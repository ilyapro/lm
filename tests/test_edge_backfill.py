def test_multi_rule_pair_collapses_to_one_row(tmp_path: Path) -> None:
    """A pair sharing both a commit and a file yields one related row."""

    with _store(tmp_path) as store:
        left = _remember(store, "left change", commit="deadbee1234", files=["src/x.py"])
        right = _remember(store, "right change", commit="deadbee1234", files=["src/x.py"])
        report = backfill_edges(store, apply=True)

        src, tgt = sorted((left.id, right.id))
        edges = store.list_connections(source_id=src, target_id=tgt, relation_type="related")
        assert len(edges) == 1  # collapsed, not two rows
        assert report["totals"]["multi_rule_rows"] >= 1
        # Both contributing rules are recorded in the sample metadata.
        merged = edges[0].metadata
        assert merged["rule_basis"] == SHARED_FILES_BASIS  # R4b applied last
        assert merged["commit"] == "deadbee"  # R4a key survives the merge
