def _snapshot(path):
    with closing(sqlite3.connect(path.as_uri() + "?mode=ro", uri=True)) as conn:
        return (
            tuple(conn.iterdump()),
            conn.execute("PRAGMA user_version").fetchone(),
            conn.execute("PRAGMA application_id").fetchone(),
        )


def _cli(path, *flags):
    env = dict(os.environ, PYTHONPATH=str(Path(__file__).resolve().parents[1] / "src"))
    return subprocess.run(
        [sys.executable, "-m", "living_memory.edge_backfill", "derive-edges",
         "--db", str(path), *flags],
        env=env, capture_output=True, text=True, timeout=30,
    )


def _capture_store(monkeypatch, apply=False):
    stores = []
    factory = "MemoryStore" if apply else "open_read_only_store"
    original = getattr(edge_backfill, factory)

    def opened(*args, **kwargs):
        store = original(*args, **kwargs)
        if not apply:
            assert store.config == kwargs["config"]
            assert args[0] == store.config.db_path
        stores.append(store)
        return store

    monkeypatch.setattr(edge_backfill, factory, opened)
    return stores


def _assert_closed(stores):
    assert len(stores) == 1
    with pytest.raises(sqlite3.ProgrammingError, match="closed"):
        stores[0].connection.execute("SELECT 1")


def test_run_backfill_preview_never_initializes_store(preview_db, monkeypatch):
    before = _snapshot(preview_db)
    stores = _capture_store(monkeypatch)

    def forbidden(*args, **kwargs):
        pytest.fail("preview called MemoryStore.__init__")

    monkeypatch.setattr(MemoryStore, "__init__", forbidden)
    report = run_backfill(preview_db)
    assert report["mode"] == "dry-run"
    assert report["applied"] is False
    assert report["totals"]["new_rows"] == 4
    _assert_closed(stores)
    assert _snapshot(preview_db) == before


@pytest.mark.parametrize("flags", [[], ["--dry-run"]])
def test_cli_preview_preserves_full_database(preview_db, tmp_path, flags):
    before = _snapshot(preview_db)
    stdout = _cli(preview_db, *flags)
    assert stdout.returncode == 0, stdout.stderr
    report = json.loads(stdout.stdout)
    assert report["mode"] == "dry-run"
    assert report["totals"]["new_rows"] == 4
    assert "[dry-run] 4 new edges" in stdout.stderr
    output = tmp_path / "reports" / "audit.json"
    saved = _cli(preview_db, *flags, "--report", str(output), "--sample-size", "1")
    assert saved.returncode == 0, saved.stderr
    assert saved.stdout == ""
    audit = json.loads(output.read_text())
    assert audit["totals"] == report["totals"]
    assert audit["sample_size"] == 1
    assert all(len(rule["samples"]) <= 1 for rule in audit["rules"].values())
    assert output.with_suffix(".md").read_text() == edge_backfill.render_markdown(audit)
    assert _snapshot(preview_db) == before
    with open_read_only_store(preview_db) as store:
        assert store.connection.execute(
            "SELECT count(*) FROM nodes WHERE content_fingerprint IS NULL"
        ).fetchone()[0] == 10


@pytest.mark.parametrize("missing_parent", [False, True])
def test_preview_rejects_missing_paths(tmp_path, missing_parent):
    parent = tmp_path / "absent" if missing_parent else tmp_path
